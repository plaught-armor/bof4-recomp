#!/usr/bin/env python3
"""Build docs/address-map.md from the port's named constants.

Every top-level Odin constant in port/src whose value is a PS1 RAM or
scratchpad address (`NAME :: 0x8xxxxxxx` or `0x1f80xxxx`) is listed, sorted by
address, with the comment on its line and the comment block just above it,
and the file and line it comes from. Constants naming the same address in
several files are merged into one row. A per-overlay enumerated array
(`NAME := [Setting_Overlay]u32{.Camp = 0x8..., .Title = 0x8...}`) lists each
element as `NAME[.Camp]`, `NAME[.Title]`.

Usage (from the repo root):
  python3 tools/address_map.py port/src docs/address-map.md
"""

import os
import re
import sys
from collections import defaultdict

CONST = re.compile(r"^([A-Z][A-Z0-9_]*)\s*::\s*(0x[0-9a-fA-F]{8})\b\s*(?://\s*(.*))?$")
ARRAY = re.compile(r"^([A-Z][A-Z0-9_]*)\s*:[:=]\s*\[[A-Za-z_]+\][a-z0-9]+\{([^}]*)\}\s*(?://\s*(.*))?$")
ELEM = re.compile(r"\.([A-Za-z_]+)\s*=\s*(0x[0-9a-fA-F]{8})\b")
ATTR = re.compile(r"^@\(")


def region(addr):
    if 0x1F800000 <= addr < 0x1F800400:
        return "Scratchpad (0x1f800000-0x1f8003ff)"
    if 0x80000000 <= addr < 0x80010000:
        return "Kernel area (0x80000000-0x8000ffff)"
    if 0x80010000 <= addr < 0x80180000:
        return "Executable SLUS_013.24 code and data (0x80010000-0x8017ffff)"
    if 0x80180000 <= addr < 0x80200000:
        return "Overlay area and heap (0x80180000-0x801fffff)"
    return None


def scan(root):
    rows = defaultdict(list)  # addr -> [(name, file, line, note)]
    for dirpath, _, files in os.walk(root):
        for f in sorted(files):
            if not f.endswith(".odin"):
                continue
            path = os.path.join(dirpath, f)
            if "/rec/" in path.replace(os.sep, "/") + "/":
                continue  # recompiled code: no hand-named addresses
            with open(path, encoding="utf-8") as fh:
                lines = fh.read().split("\n")
            for i, line in enumerate(lines):
                m = CONST.match(line)
                if m:
                    found = [(m.group(1), int(m.group(2), 16))]
                elif a := ARRAY.match(line):
                    m = a
                    found = [(f"{a.group(1)}[.{e[0]}]", int(e[1], 16)) for e in ELEM.findall(a.group(2))]
                else:
                    continue
                found = [(n, addr) for n, addr in found if region(addr) is not None]
                if not found:
                    continue
                above = []
                j = i - 1
                while j >= 0 and ATTR.match(lines[j].strip()):
                    j -= 1
                while j >= 0 and lines[j].startswith("//"):
                    above.insert(0, lines[j][2:].strip())
                    j -= 1
                note = " ".join(x for x in [" ".join(above), m.group(3) or ""] if x)
                rel = os.path.relpath(path, os.path.dirname(os.path.abspath(root)))
                for name, addr in found:
                    rows[addr].append((name, rel, i + 1, note.strip()))
    return rows


def cell(s):
    return s.replace("|", "\\|").replace("\n", " ")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    rows = scan(sys.argv[1])
    by_region = defaultdict(list)
    for addr in sorted(rows):
        by_region[region(addr)].append(addr)
    out = [
        "# Address map",
        "",
        "Generated by `tools/address_map.py` from the named constants in `port/src`;",
        "do not edit by hand. Every address here is one the port reads, writes, hooks",
        "or calls, named and described where it is used. Overlay addresses are only",
        "valid while that overlay is loaded (see [overlays.md](overlays.md)).",
        "",
        f"{len(rows)} addresses.",
        "",
    ]
    for reg in sorted(by_region, key=lambda r: min(by_region[r])):
        out += [f"## {reg}", "", "| Address | Name | Notes | Source |", "|---|---|---|---|"]
        for addr in by_region[reg]:
            entries = rows[addr]
            names = ", ".join(sorted({e[0] for e in entries}))
            notes = " / ".join(dict.fromkeys(e[3] for e in entries if e[3]))
            src = "<br>".join(f"`{e[1]}:{e[2]}`" for e in entries)
            out.append(f"| `{addr:08x}` | {cell(names)} | {cell(notes)} | {src} |")
        out.append("")
    with open(sys.argv[2], "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(f"{len(rows)} addresses -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
